import re
import logging

def dictionary_declensions(text):
    city_replacements = {
        "киеве": "киев",
        "париже": "париж",
        "москве": "москва",
        "пекине": "пекин",
        "днепре": "днепр",
        "днепропетровске": "днепропетровск",
        "лондоне": "лондон",
        "берлине": "берлин",
        "токио": "токио",
        "риме": "рим",
        "мадриде": "мадрид",
        "сиднее": "сидней",
        "вашингтоне": "вашингтон",
        "оттаве": "оттава",
        "амстердаме": "амстердам",
        "дублине": "дублин",
        "пражке": "прага",
        "вене": "вена",
        "сеуле": "сеул",
        "бангкоке": "бангкок",
        "брюсселе": "брюссель",
        "копенгагене": "копенгаген",
        "стокгольме": "стокгольм",
        "хельсинки": "хельсинки",
        "осло": "осло",
        "лиссабоне": "лиссабон",
        "афинах": "афины",
        "будапеште": "будапешт",
        "варшаве": "варшава",
        "минске": "минск",
        "тбилиси": "тбилиси",
        "ереване": "ереван",
        "баку": "баку",
        "астане": "астана",
        "шутку": "шутка",
        "доллара": "доллар",
        "гривны": "гривна",
        "черт": "чёрт",
    }

    number_replacements = {
        "ноль": "0",
        "один": "1",
        "два": "2",
        "три": "3",
        "четыре": "4",
        "пять": "5",
        "шесть": "6",
        "семь": "7",
        "восемь": "8",
        "девять": "9",
        "десять": "10",
        "одиннадцать": "11",
        "двенадцать": "12",
        "тринадцать": "13",
        "четырнадцать": "14",
        "пятнадцать": "15",
        "шестнадцать": "16",
        "семнадцать": "17",
        "восемнадцать": "18",
        "девятнадцать": "19",
        "двадцать": "20",
        "тридцать": "30",
        "сорок": "40",
        "пятьдесят": "50"
    }

    # Сначала заменяем словесные числа на цифры
    for word, number in number_replacements.items():
        text = re.sub(rf"\b{word}\b", number, text, flags=re.IGNORECASE)

    # Обрабатываем время дня с минутами
    time_patterns = [
        # Часы дня/вечера с минутами
        (r'(\d+)\s*час[ао]?в?\s*(дня|вечера)(?:\s+(\d+)\s*минут)?', 
         lambda m: f"{int(m.group(1))+12}:{m.group(3) if m.group(3) else '00'}"),
        # Часы утра с минутами
        (r'(\d+)\s*час[ао]?в?\s*утра(?:\s+(\d+)\s*минут)?', 
         lambda m: f"{int(m.group(1)):02d}:{m.group(2) if m.group(2) else '00'}"),
        # Просто часы с минутами
        (r'(\d+)\s*час[ао]?в?(?:\s+(\d+)\s*минут)?', 
         lambda m: f"{int(m.group(1)):02d}:{m.group(2) if m.group(2) else '00'}")
    ]

    # Обрабатываем время дня
    for pattern, replacement in time_patterns:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)

    # Обработка городов и других замен
    pattern = re.compile("|".join(map(re.escape, city_replacements.keys())))
    text = pattern.sub(lambda match: city_replacements[match.group(0)], text)

    return text
