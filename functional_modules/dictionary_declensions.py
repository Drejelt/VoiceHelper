import re

def dictionary_declensions(text):
    city_replacements = {
        "киеве": "киев",
        "париже": "париж",
        "москве": "москва",
        "пекине": "пекин",
        "днепре": "днепр",
        "днепропетровске": "днепропетровск",
        "лондоне": "лондон",
        "берлине": "берлин",
        "токио": "токио",
        "риме": "рим",
        "мадриде": "мадрид",
        "сиднее": "сидней",
        "вашингтоне": "вашингтон",
        "оттаве": "оттава",
        "амстердаме": "амстердам",
        "дублине": "дублин",
        "пражке": "прага",
        "вене": "вена",
        "сеуле": "сеул",
        "бангкоке": "бангкок",
        "брюсселе": "брюссель",
        "копенгагене": "копенгаген",
        "стокгольме": "стокгольм",
        "хельсинки": "хельсинки",
        "осло": "осло",
        "лиссабоне": "лиссабон",
        "афинах": "афины",
        "будапеште": "будапешт",
        "варшаве": "варшава",
        "минске": "минск",
        "тбилиси": "тбилиси",
        "ереване": "ереван",
        "баку": "баку",
        "астане": "астана",
        "шутку": "шутка",
        "доллара": "доллар",
        "гривны": "гривна",
        "черт": "чёрт",
    }

    number_replacements = {
        "ноль": "0",
        "один": "1",
        "два": "2",
        "три": "3",
        "четыре": "4",
        "пять": "5",
        "шесть": "6",
        "семь": "7",
        "восемь": "8",
        "девять": "9",
        "десять": "10",
        "одиннадцать": "11",
        "двенадцать": "12",
    }

    def replace_numbers(match):
        return number_replacements.get(match.group(0), match.group(0))

    def normalize_time(match):
        hour = int(match.group(1))
        if "вечера" in match.group(2) or "дня" in match.group(2):
            if hour < 12:
                hour += 12
        elif "утра" in match.group(2) and hour == 12:
            hour = 0
        return f"{hour:02d}:00"

    # Заменяем числовые слова на цифры
    for word, number in number_replacements.items():
        text = re.sub(rf"\b{word}\b", number, text)

    # Преобразуем временные выражения
    text = re.sub(r"(\d+)\s*(часов|часа|час|утра|вечера|дня)", normalize_time, text)

    # Обработка городов и других замен
    pattern = re.compile("|".join(map(re.escape, city_replacements.keys())))
    text = pattern.sub(lambda match: city_replacements[match.group(0)], text)

    return text
